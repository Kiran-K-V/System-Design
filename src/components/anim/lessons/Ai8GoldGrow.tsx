import AnimFrame from '../AnimFrame';
import { HandText, SketchBox, SketchSvg, TEXT_SIZES, seedOf } from '../sketch';

// Illustrative support-bot set. Rows are scenarios, columns are how the request is worded.
const ROWS = ['Refund', 'Order status', 'Address change', 'Warranty', 'Hostile user'];
const COLS = ['Typical', 'Messy', 'Edge case'];
const REAL = [
  [22, 9, 3],
  [14, 5, 0],
  [6, 2, 0],
  [4, 0, 0],
  [0, 3, 0],
];
const FLOOR = 3;
const SYN = REAL.map((r) => r.map((n) => Math.max(0, FLOOR - n)));
const sum = (m: number[][]) => m.flat().reduce((a, b) => a + b, 0);
const REAL_N = sum(REAL); // 68
const SYN_N = sum(SYN); // 19
const ALL = REAL_N + SYN_N; // 87
const DEV = 44;

type Phase = 'real' | 'gaps' | 'fill' | 'split' | 'version';
interface Step {
  caption: string;
  phase: Phase;
}

const steps: Step[] = [
  { caption: `Start with real traces. These ${REAL_N} cases come from error analysis. Each case is tagged with its scenario (row) and how the request is worded (column). The numbers are illustrative.`, phase: 'real' },
  { caption: 'Read the coverage. Red dashed cells have no case. Orange cells have one or two. Refund with typical wording has 22 cases, and warranty with messy wording has none. One pass rate over all cases would mostly measure refunds.', phase: 'gaps' },
  { caption: `Fill the gaps with synthetic cases, written by a person or generated by a model from a list of scenarios. The rule here is at least ${FLOOR} cases per cell. That adds ${SYN_N} cases (in the accent color), for ${ALL} in total. Real cases still make up most of the set.`, phase: 'fill' },
  { caption: `Split the set. Tune the prompt on the dev half (${DEV} cases). Keep the test half (${ALL - DEV} cases) untouched until you need an honest score. If you tune on every case, the score measures memory, not skill.`, phase: 'split' },
  { caption: 'Version the set. Call it golden-v1 and never edit it in place. A change makes golden-v2 with a note on what was added or fixed. Then an old score and a new score are only compared when they used the same version.', phase: 'version' },
];

const CX = [300, 430, 560];
const RY = (r: number) => 96 + r * 50;

function tone(n: number) {
  return n === 0 ? 'var(--bad)' : n < FLOOR ? 'var(--warn)' : 'var(--ok)';
}

export default function Ai8GoldGrow() {
  return (
    <AnimFrame title="A golden set grows from traces" steps={steps} interval={5600}>
      {(i, s) => {
        const grid = s.phase === 'real' || s.phase === 'gaps' || s.phase === 'fill';
        return (
          <SketchSvg width={720} height={340} label={`Step ${i + 1}: ${s.phase}`}>
            {grid && (
              <>
                {COLS.map((c, k) => (
                  <HandText key={c} x={CX[k]} y={46} size={TEXT_SIZES.heading} color="var(--muted)">{c}</HandText>
                ))}
                <HandText x={650} y={46} size={TEXT_SIZES.heading} color="var(--muted)">Total</HandText>
                {ROWS.map((r, ri) => (
                  <g key={r}>
                    <HandText x={30} y={RY(ri)} anchor="start" size={TEXT_SIZES.label}>{r}</HandText>
                    {COLS.map((_, ci) => {
                      const real = REAL[ri][ci];
                      const syn = SYN[ri][ci];
                      const filled = s.phase === 'fill';
                      const n = real + (filled ? syn : 0);
                      const t = s.phase === 'real' ? 'var(--fg)' : tone(n);
                      const added = filled && syn > 0;
                      return (
                        <g key={ci}>
                          <SketchBox cx={CX[ci]} cy={RY(ri)} w={110} h={40} r={8} seed={seedOf(`gg${ri}${ci}`)} stroke={added ? 'var(--accent)' : t} fill={s.phase === 'real' ? undefined : t} dashed={s.phase === 'gaps' && n === 0} strokeWidth={added ? 2.2 : 1.4} />
                          <HandText x={CX[ci]} y={RY(ri)} size={TEXT_SIZES.label} mono>{added ? `${real} + ${syn}` : String(real)}</HandText>
                        </g>
                      );
                    })}
                    <HandText x={650} y={RY(ri)} size={TEXT_SIZES.label} mono color="var(--muted)">
                      {String(REAL[ri].reduce((a, b) => a + b, 0) + (s.phase === 'fill' ? SYN[ri].reduce((a, b) => a + b, 0) : 0))}
                    </HandText>
                  </g>
                ))}
                <HandText x={30} y={326} anchor="start" size={TEXT_SIZES.note} color="var(--muted)">
                  {s.phase === 'fill' ? `${REAL_N} real + ${SYN_N} synthetic = ${ALL} cases` : `${REAL_N} real cases`}
                </HandText>
              </>
            )}
            {s.phase === 'split' && (
              <>
                <HandText x={360} y={60} size={TEXT_SIZES.heading} color="var(--muted)">{`${ALL} labeled cases`}</HandText>
                <SketchBox cx={40 + ((DEV / ALL) * 640) / 2} cy={140} w={(DEV / ALL) * 640} h={60} r={8} seed={seedOf('gs-dev')} stroke="var(--accent)" fill="var(--accent)" strokeWidth={2.2} />
                <SketchBox cx={40 + (DEV / ALL) * 640 + (((ALL - DEV) / ALL) * 640) / 2} cy={140} w={((ALL - DEV) / ALL) * 640} h={60} r={8} seed={seedOf('gs-test')} stroke="var(--ok)" fill="var(--ok)" />
                <HandText x={40 + ((DEV / ALL) * 640) / 2} y={140} size={TEXT_SIZES.label}>{`dev ${DEV}`}</HandText>
                <HandText x={40 + (DEV / ALL) * 640 + (((ALL - DEV) / ALL) * 640) / 2} y={140} size={TEXT_SIZES.label}>{`test ${ALL - DEV}`}</HandText>
                <HandText x={40 + ((DEV / ALL) * 640) / 2} y={200} size={TEXT_SIZES.note} color="var(--muted)">edit the prompt against these</HandText>
                <HandText x={40 + (DEV / ALL) * 640 + (((ALL - DEV) / ALL) * 640) / 2} y={200} size={TEXT_SIZES.note} color="var(--muted)">look only at release time</HandText>
              </>
            )}
            {s.phase === 'version' && (
              <>
                <SketchBox cx={360} cy={150} w={440} h={170} r={8} seed={seedOf('gv-box')} stroke="var(--ok)" fill="var(--ok)" strokeWidth={2.2} />
                <HandText x={360} y={96} size={TEXT_SIZES.title} mono>golden-v1</HandText>
                <HandText x={360} y={140} size={TEXT_SIZES.label}>{`${ALL} cases: ${REAL_N} real, ${SYN_N} synthetic`}</HandText>
                <HandText x={360} y={172} size={TEXT_SIZES.label}>{`dev ${DEV} and test ${ALL - DEV}`}</HandText>
                <HandText x={360} y={204} size={TEXT_SIZES.label}>never edited in place</HandText>
              </>
            )}
          </SketchSvg>
        );
      }}
    </AnimFrame>
  );
}
